"""Порядок показа вариантов ответа.

В банке верный вариант записан первым, поэтому без перестановки он всегда
оказывается под номером один и подсказывает ответ. Порядок показа —
детерминированная функция от ключа выдачи, а не результат глобального ГПСЧ:
повторная отрисовка того же вопроса (продолжение сессии, перерисовка
экрана-якоря после перезапуска) даёт тот же порядок, и хранить перестановку
не нужно.
"""

from __future__ import annotations

import random

#: Ключ выдачи: то, что однозначно определяет один показ вопроса.
IssueKey = tuple[object, ...]

#: Буквы вариантов — участнику проще сослаться на «Б», чем на «второй».
OPTION_LABELS = "АБВГДЕЁЖЗИ"


def display_order(count: int, key: IssueKey) -> list[int]:
    """Порядок показа как список исходных индексов вариантов.

    Одинаковый `key` при одинаковом `count` всегда даёт один и тот же порядок.
    """
    order = list(range(count))
    random.Random(repr(key)).shuffle(order)
    return order


def shuffled_order(count: int) -> list[int]:
    """Случайный порядок показа без привязки к ключу.

    Для группового опроса: он уходит в Telegram один раз, воспроизводить
    порядок незачем.
    """
    order = list(range(count))
    random.shuffle(order)
    return order


def labelled_order(count: int, key: IssueKey) -> list[tuple[str, int]]:
    """Порядок показа как пары «буква — исходный индекс варианта».

    Буква назначается здесь и только здесь: список вариантов в тексте
    сообщения и ряд кнопок под ним собираются из одного её вызова, поэтому
    буква на кнопке не может разойтись со строкой списка.
    """
    return list(zip(OPTION_LABELS, display_order(count, key), strict=False))
